// Checks the evaluation set against the collected scans: every anchor must name an element
// that the extension actually saw, and no scenario may ask to keep something inside a region it
// asks to hide. Run from the repo root:  node evaluation/validate.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { resolveAnchor } from "../extension/src/shared/anchors.ts";
import type { Anchor, Scenario } from "../extension/src/shared/anchors.ts";
import type { PageScan, ScanNode } from "../extension/src/shared/types.ts";

const root = path.dirname(new URL(import.meta.url).pathname);
const scenarios = JSON.parse(readFileSync(path.join(root, "scenarios.json"), "utf8")) as Array<Scenario>;

function scanFor(site: string): PageScan | undefined {
  const file = path.join(root, "snapshots", site, "scan.json");
  return existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as PageScan) : undefined;
}

function inside(node: ScanNode, ancestor: ScanNode, nodes: Array<ScanNode>): boolean {
  const byId = new Map(nodes.map((candidate) => [candidate.id, candidate]));
  for (let current: string | undefined = node.id; current; current = byId.get(current)?.parent)
    if (current === ancestor.id) return true;
  return false;
}

const describe = (anchor: Anchor) => JSON.stringify(anchor);
const rows: Array<string> = [];
let problems = 0;
let checked = 0;

for (const scenario of scenarios) {
  if (scenario.requires === "real-browser") {
    rows.push(`| ${scenario.id} | ${scenario.site} | real browser only | not validated |`);
    continue;
  }
  const scan = scanFor(scenario.site);
  if (!scan) {
    problems += 1;
    rows.push(`| ${scenario.id} | ${scenario.site} | **no snapshot** | run the collector |`);
    continue;
  }
  const issues: Array<string> = [];
  const anchors = [...(scenario.pick ? [{ op: "pick", anchor: scenario.pick }] : []), ...scenario.expect];
  const resolved = new Map<Anchor, ScanNode>();
  for (const { op, anchor } of anchors) {
    checked += 1;
    const { node, matches } = resolveAnchor(scan.nodes, anchor);
    if (!node) issues.push(`${op} ${describe(anchor)} matches nothing`);
    else resolved.set(anchor, node);
    if (matches > 3) issues.push(`${op} ${describe(anchor)} is loose (${matches} matches)`);
  }
  for (const keep of scenario.expect.filter((expectation) => expectation.op === "keep"))
    for (const hide of scenario.expect.filter((expectation) => expectation.op === "hide")) {
      const kept = resolved.get(keep.anchor);
      const hidden = resolved.get(hide.anchor);
      if (kept && hidden && inside(kept, hidden, scan.nodes))
        issues.push(`keep ${describe(keep.anchor)} lies inside hide ${describe(hide.anchor)}`);
    }
  problems += issues.length;
  rows.push(`| ${scenario.id} | ${scenario.site} | ${anchors.length} anchors | ${issues.length > 0 ? issues.join("; ") : "ok"} |`);
}

const report = [
  "# Evaluation set validation",
  "",
  `Generated by \`node evaluation/validate.ts\` against \`evaluation/snapshots/\`. ${checked} anchors checked, ${problems} problems.`,
  "",
  "| Scenario | Site | Anchors | Result |",
  "|---|---|---|---|",
  ...rows,
  "",
].join("\n");
writeFileSync(path.join(root, "validation.md"), report);
console.log(report);
process.exitCode = problems > 0 ? 1 : 0;
