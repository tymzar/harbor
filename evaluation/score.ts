// Summarises an evaluation run (evaluation/runs/<run>/*.json, written by the runner in
// extension/e2e-tests/eval-run.spec.ts) into evaluation/runs/<run>/report.md.
// Run from the repo root:  node evaluation/score.ts <run>
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import type { ExpectedOp, Scenario, Verdict } from "../extension/src/shared/anchors.ts";
import type { CallLog } from "../extension/src/shared/types.ts";

type ModeRun = {
  mode: string;
  proposal?: { status: string; error?: string; errors?: Array<string>; repaired: boolean; calls: Array<CallLog>; ms: number; accepted?: Array<{ operation: string }> };
  layout?: { labels: Array<string>; missing: Array<string> };
  notice?: string;
  error?: string;
  verdicts: Array<Verdict>;
};
type Result = { scenario: Scenario; rescanned: boolean; baseline: Array<Verdict>; runs: Array<ModeRun> };

const root = path.dirname(new URL(import.meta.url).pathname);
const run = process.argv[2];
if (!run) throw new Error("usage: node evaluation/score.ts <run>");
const dir = path.join(root, "runs", run);
const results = readdirSync(dir)
  .filter((file) => file.endsWith(".json"))
  .map((file) => JSON.parse(readFileSync(path.join(dir, file), "utf8")) as Result)
  .sort((a, b) => a.scenario.id.localeCompare(b.scenario.id));

const OPS: Array<ExpectedOp> = ["hide", "keep", "emphasize", "compact", "grid"];
const percent = (part: number, whole: number) => (whole === 0 ? "–" : `${Math.round((100 * part) / whole)}% (${part}/${whole})`);
const median = (values: Array<number>) => {
  const sorted = values.toSorted((a, b) => a - b);
  return sorted.length === 0 ? 0 : sorted[Math.floor(sorted.length / 2)];
};
const sum = (values: Array<number | undefined>) => values.reduce<number>((total, value) => total + (value ?? 0), 0);

// One column per way of running a scenario: the untouched page, then each mode.
type Column = { name: string; entries: Array<{ result: Result; verdicts: Array<Verdict>; run?: ModeRun }> };
const usable = results.filter((result) => !result.rescanned);
const goalResults = usable.filter((result) => result.scenario.goal);
const modes = [...new Set(usable.flatMap((result) => result.runs.map((entry) => entry.mode)))];
const columns: Array<Column> = [
  { name: "do nothing (goal scenarios)", entries: goalResults.map((result) => ({ result, verdicts: result.baseline })) },
  ...modes.map((mode) => ({
    name: mode,
    entries: usable.flatMap((result) => {
      const entry = result.runs.find((candidate) => candidate.mode === mode);
      return entry ? [{ result, verdicts: entry.verdicts, run: entry }] : [];
    }),
  })),
];

function rate(column: Column, filter: (op: ExpectedOp) => boolean) {
  let passed = 0;
  let scored = 0;
  for (const { result, verdicts } of column.entries)
    for (const [index, verdict] of verdicts.entries()) {
      if (!filter(result.scenario.expect[index].op) || (verdict !== "pass" && verdict !== "fail")) continue;
      scored += 1;
      if (verdict === "pass") passed += 1;
    }
  return { passed, scored };
}

const scoredOnly = (verdicts: Array<Verdict>) => verdicts.filter((verdict) => verdict === "pass" || verdict === "fail");

const lines: Array<string> = [
  `# Evaluation run ${run}`,
  "",
  `Generated by \`node evaluation/score.ts ${run}\` from ${results.length} scenario results` +
    (results.length === usable.length ? "." : `; ${results.length - usable.length} left out because the page was rescanned mid-run.`),
  "",
  "Expectations whose element was not on the page this visit (`unresolved`), or was already hidden before any change (`not-visible`), are not scored.",
  "",
  "## Outcomes",
  "",
  `| | ${columns.map((column) => column.name).join(" | ")} |`,
  `|---|${columns.map(() => "---").join("|")}|`,
  `| Scenarios | ${columns.map((column) => column.entries.length).join(" | ")} |`,
];
const row = (name: string, cell: (column: Column) => string) => lines.push(`| ${name} | ${columns.map((column) => cell(column)).join(" | ")} |`);
row("Expectations passed", (column) => {
  const { passed, scored } = rate(column, () => true);
  return percent(passed, scored);
});
row("Scenarios fully passed", (column) => {
  const judged = column.entries.filter((entry) => scoredOnly(entry.verdicts).length > 0);
  return percent(judged.filter((entry) => scoredOnly(entry.verdicts).every((verdict) => verdict === "pass")).length, judged.length);
});
for (const op of OPS)
  row(op === "keep" ? "keep (not over-hidden)" : op, (column) => {
    const { passed, scored } = rate(column, (candidate) => candidate === op);
    return percent(passed, scored);
  });
row("Unresolved / not visible", (column) => {
  const all = column.entries.flatMap((entry) => entry.verdicts);
  return `${all.filter((verdict) => verdict === "unresolved").length} / ${all.filter((verdict) => verdict === "not-visible").length}`;
});

lines.push("", "## Cost and speed", "", "| | " + modes.join(" | ") + " |", `|---|${modes.map(() => "---").join("|")}|`);
const modeColumns = columns.slice(1);
const modeRow = (name: string, cell: (runs: Array<ModeRun>) => string) =>
  lines.push(`| ${name} | ${modeColumns.map((column) => cell(column.entries.flatMap((entry) => (entry.run?.proposal ? [entry.run] : [])))).join(" | ")} |`);
modeRow("Plans asked for", (runs) => String(runs.length));
modeRow("Plan errors", (runs) => String(runs.filter((entry) => entry.proposal!.status !== "done").length));
modeRow("Repair rounds", (runs) => String(runs.filter((entry) => entry.proposal!.repaired).length));
modeRow("Plans with validator rejections left", (runs) => String(runs.filter((entry) => (entry.proposal!.errors?.length ?? 0) > 0).length));
modeRow("Plans with no visible change", (runs) =>
  String(runs.filter((entry) => !entry.proposal!.accepted?.some((group) => group.operation !== "none")).length)
);
modeRow("Median time to plan (s)", (runs) => (median(runs.map((entry) => entry.proposal!.ms)) / 1000).toFixed(1));
const calls = (runs: Array<ModeRun>, model: RegExp) => runs.flatMap((entry) => entry.proposal!.calls.filter((call) => model.test(call.model)));
modeRow("Spark calls", (runs) => String(calls(runs, /spark/).length));
modeRow("Spark input / output / reasoning tokens", (runs) => {
  const spark = calls(runs, /spark/);
  return `${sum(spark.map((call) => call.inputTokens))} / ${sum(spark.map((call) => call.outputTokens))} / ${sum(spark.map((call) => call.reasoningTokens))}`;
});
modeRow("Median Spark call (s)", (runs) => (median(calls(runs, /spark/).map((call) => call.ms)) / 1000).toFixed(1));
modeRow("SAM calls", (runs) => String(calls(runs, /sam/).length));
modeRow("Median SAM call (s)", (runs) => (median(calls(runs, /sam/).map((call) => call.ms)) / 1000).toFixed(1));

const mark = (verdict: Verdict) => ({ pass: "✓", fail: "✗", unresolved: "?", "not-visible": "–" })[verdict];
lines.push(
  "",
  "## Per scenario",
  "",
  "✓ pass, ✗ fail, ? element not found this visit, – already hidden before any change. One mark per expectation, in `scenarios.json` order.",
  "",
  `| Scenario | Ops | do nothing | ${modes.join(" | ")} |`,
  `|---|---|---|${modes.map(() => "---").join("|")}|`
);
for (const result of results) {
  const ops = result.scenario.expect.map((item) => item.op).join(" ");
  const cells = modes.map((mode) => {
    const entry = result.runs.find((candidate) => candidate.mode === mode);
    if (!entry) return "";
    const problem = entry.proposal?.error ?? entry.error ?? entry.notice;
    return entry.verdicts.map((verdict) => mark(verdict)).join("") + (problem ? ` (${problem.slice(0, 60)})` : "");
  });
  const id = result.rescanned ? `${result.scenario.id} (rescanned, not scored)` : result.scenario.id;
  lines.push(`| ${id} | ${ops} | ${result.scenario.goal ? result.baseline.map((verdict) => mark(verdict)).join("") : ""} | ${cells.join(" | ")} |`);
}
lines.push("");

const report = lines.join("\n");
writeFileSync(path.join(dir, "report.md"), report);
console.log(report);
